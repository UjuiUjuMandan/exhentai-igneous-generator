function randomizeHostBits(cidr) {
  const [network, prefixStr] = cidr.split('/');
  const prefix = parseInt(prefixStr, 10);

  if (network.includes(':')) {
    // IPv6: Expand to 8 16-bit groups, then randomize every bit past
    // the prefix length across those groups.
    const [head, tail = ''] = network.split('::');
    const headGroups = head ? head.split(':') : [];
    const tailGroups = network.includes('::') && tail ? tail.split(':') : [];
    const missing = 8 - headGroups.length - tailGroups.length;
    const groups = (
      network.includes('::')
        ? [...headGroups, ...Array(missing).fill('0'), ...tailGroups]
        : network.split(':')
    ).map((g) => parseInt(g, 16));

    for (let i = 0; i < 8; i++) {
      const groupStart = i * 16;
      const groupEnd = groupStart + 16;
      const fixedBits = Math.max(0, Math.min(16, prefix - groupStart));
      const randomBits = 16 - fixedBits;
      if (randomBits <= 0) continue;
      const mask = (1 << randomBits) - 1;
      const randomPart = Math.floor(Math.random() * (mask + 1));
      groups[i] = (groups[i] & ~mask) | randomPart;
    }
    return groups.map((g) => g.toString(16)).join(':');
  }

  // IPv4: randomize every bit past the prefix length across the 32-bit
  // address, expressed as 4 octets.
  const octets = network.split('.').map(Number);
  let addr =
    ((octets[0] << 24) | (octets[1] << 16) | (octets[2] << 8) | octets[3]) >>>
    0;
  const hostBits = 32 - prefix;
  if (hostBits > 0) {
    const mask = hostBits >= 32 ? 0xffffffff : (1 << hostBits) - 1;
    const randomPart = Math.floor(Math.random() * (mask + 1)) >>> 0;
    addr = ((addr & ~mask) | randomPart) >>> 0;
  }
  return [
    (addr >>> 24) & 0xff,
    (addr >>> 16) & 0xff,
    (addr >>> 8) & 0xff,
    addr & 0xff,
  ].join('.');
}

function generateUsWarpIp() {
  const choices = ['8', 'a', 'c', 'e'];
  const x = choices[Math.floor(Math.random() * choices.length)];
  const cityFirstNibble = Math.floor(Math.random() * 10).toString(16);
  const cityRest = Math.floor(Math.random() * 0x1000)
    .toString(16)
    .padStart(3, '0');
  const rand7 = Math.floor(Math.random() * 0x1000)
    .toString(16)
    .padStart(3, '0');
  const rand8 = Math.floor(Math.random() * 0x1000)
    .toString(16)
    .padStart(3, '0');
  return `2a09:bac1:76${x}0:${cityFirstNibble}${cityRest}:0000:0000:0${rand7}:0${rand8}`;
}

